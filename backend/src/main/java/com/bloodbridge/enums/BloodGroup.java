package com.bloodbridge.enums;

/**
 * Enumeration representing blood groups in the Blood Bridge system.
 */
public enum BloodGroup {
    /**
     * A+ blood type.
     */
    A_POSITIVE,

    /**
     * A- blood type.
     */
    A_NEGATIVE,

    /**
     * B+ blood type.
     */
    B_POSITIVE,

    /**
     * B- blood type.
     */
    B_NEGATIVE,

    /**
     * AB+ blood type.
     */
    AB_POSITIVE,

    /**
     * AB- blood type.
     */
    AB_NEGATIVE,

    /**
     * O+ blood type.
     */
    O_POSITIVE,

    /**
     * O- blood type.
     */
    O_NEGATIVE
}
